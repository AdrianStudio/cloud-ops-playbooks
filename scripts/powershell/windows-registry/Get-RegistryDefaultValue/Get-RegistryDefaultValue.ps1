<#
.SYNOPSIS
    Retrieves the default value for specified registry keys from a clean Windows installation.

.DESCRIPTION
    This script connects to a clean Windows installation (local or remote) and queries the default
    values for a list of specified registry keys. It compares these defaults with the current
    values on the target system and can optionally generate a remediation script to restore
    the default values.

.PARAMETER RegistryKeys
    An array of registry key paths (e.g., 'HKLM:\SOFTWARE\Policies\Microsoft\Windows NT\Printers\PointAndPrint').
    Each key path should include the hive.

.PARAMETER ReferenceComputerName
    The hostname or IP address of a clean Windows installation to use as a reference for default values.
    If not specified, the local machine is used as the reference.

.PARAMETER Apply
    If specified, the script will generate a PowerShell script to revert the registry values
    on the target system to their default settings. This script will be saved to the current directory.

.EXAMPLE
    Get-RegistryDefaultValue -RegistryKeys 'HKLM:\SOFTWARE\Policies\Microsoft\Windows NT\Printers\PointAndPrint\RestrictDriverInstallationToAdministrators'

.EXAMPLE
    Get-RegistryDefaultValue -RegistryKeys 'HKLM:\SOFTWARE\Policies\Microsoft\Windows NT\Printers\PointAndPrint\RestrictDriverInstallationToAdministrators', 'HKLM:\SOFTWARE\Policies\Microsoft\Windows NT\Printers\PointAndPrint\NoWarningNoElevationOnInstall' -ReferenceComputerName 'CleanVM01'

.EXAMPLE
    Get-RegistryDefaultValue -RegistryKeys 'HKLM:\SOFTWARE\Policies\Microsoft\Windows NT\Printers\PointAndPrint\RestrictDriverInstallationToAdministrators' -Apply
#>
function Get-RegistryDefaultValue {
    [CmdletBinding(SupportsShouldProcess = $true)]
    param (
        [Parameter(Mandatory = $true)]
        [string[]]$RegistryKeys,

        [string]$ReferenceComputerName,

        [switch]$Apply
    )

    $results = @()
    $remediationScriptContent = @()
    $remediationScriptContent += "# This script was generated by Get-RegistryDefaultValue to restore default registry settings."
    $remediationScriptContent += "# Run with Administrator privileges."
    $remediationScriptContent += "`n"

    foreach ($keyPath in $RegistryKeys) {
        try {
            $hive = $keyPath.Split(':')[0]
            $subKey = $keyPath.Split(':')[1]

            # Get current value
            $currentValue = Get-ItemProperty -Path $keyPath -ErrorAction Stop | Select-Object -ExpandProperty (Get-Item -Path $keyPath).Property | Select-Object -First 1

            # Get default value from reference machine
            $defaultValue = $null
            if ($PSCmdlet.ShouldProcess("Querying default value for '$keyPath' from reference machine '$($ReferenceComputerName -replace '^$', 'localhost')'")) {
                if ($ReferenceComputerName) {
                    # Attempt to get value from remote reference machine
                    # This assumes PSRemoting is enabled and configured on the reference machine
                    $scriptBlock = [scriptblock]::Create("Get-ItemProperty -Path '$keyPath' -ErrorAction Stop | Select-Object -ExpandProperty (Get-Item -Path '$keyPath').Property | Select-Object -First 1")
                    $defaultValue = Invoke-Command -ComputerName $ReferenceComputerName -ScriptBlock $scriptBlock -ErrorAction Stop
                } else {
                    # Get value from local machine if no reference specified
                    $defaultValue = Get-ItemProperty -Path $keyPath -ErrorAction Stop | Select-Object -ExpandProperty (Get-Item -Path $keyPath).Property | Select-Object -First 1
                }
            }

            $result = [PSCustomObject]@{ 
                RegistryKey = $keyPath
                CurrentValue = $currentValue
                DefaultValue = $defaultValue
                IsModified = ($currentValue -ne $defaultValue)
            }
            $results += $result

            if ($Apply -and $result.IsModified) {
                $remediationScriptContent += "Set-ItemProperty -Path '$keyPath' -Value '$($defaultValue)' -Force -ErrorAction Stop"
            }
        }
        catch [System.Management.Automation.ItemNotFoundException], [System.UnauthorizedAccessException], [System.Management.Automation.RemoteException] {
            Write-Warning "Could not process registry key '$keyPath': $($_.Exception.Message)"
            $results += [PSCustomObject]@{ 
                RegistryKey = $keyPath
                CurrentValue = "Error"
                DefaultValue = "Error"
                IsModified = $true
            }
        }
    }

    $results | Format-Table -AutoSize

    if ($Apply -and $remediationScriptContent.Count -gt 3) { # Check if any remediation lines were added beyond the header
        $outputPath = Join-Path $PSScriptRoot "Restore-RegistryDefaults.ps1"
        $remediationScriptContent | Out-File -FilePath $outputPath -Encoding UTF8 -Force
        Write-Host "`nRemediation script generated: $outputPath"
    }
    elseif ($Apply) {
        Write-Host "`nNo modifications found, no remediation script generated."
    }
}
